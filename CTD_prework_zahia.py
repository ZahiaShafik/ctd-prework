# Ask for a customer's name and loyalty points.
# Customers with 100 or more points earn a reward.

# Ask for a non-empty name.
name = input("Enter your name: ").strip()

while not name:
    name = input("Your name cannot be empty. Enter your name: ").strip()

# Keep asking until the points are a non-negative whole number.
while True:
    try:
        points = int(input("Enter your points (for example, 70): "))

        if points < 0:
            print(
                "Points cannot be negative. "
                "Please enter 0 or a positive whole number."
            )
        else:
            break

    except ValueError:
        print(
            "Please enter a whole number, like 70. "
            "Do not use words or decimals."
        )

# Check whether the customer has enough points for a reward.
if points >= 100:
    print(f"Hi {name}! You have {points} points. You earned a reward!")
else:
    remaining = 100 - points
    print(
        f"Hi {name}! You have {points} points. "
        "You need 100 points for a reward. "
        f"Collect {remaining} more points to earn one."
    )

# Example run 1
# Inputs: nervana, 120
# Output: Hi nervana! You have 120 points. You earned a reward!

